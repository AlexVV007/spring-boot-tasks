CREATE TABLE IF NOT EXISTS tasks
(
    taskid bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    userid bigint NOT NULL,
    tasktext character varying(255) NOT NULL,
    createdate date NOT NULL,
    actiondate date,
    iscomplete boolean NOT NULL,
    isdeleted boolean NOT NULL,

    CONSTRAINT tasks_pkey PRIMARY KEY (taskid)
)

CREATE TABLE IF NOT EXISTS notifications
(
    notificationid bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    text character varying(500) NOT NULL,
    isread boolean NOT NULL,
    taskid bigint NOT NULL,
    userid bigint NOT NULL,
    CONSTRAINT notifications_pkey PRIMARY KEY (notificationid)
)

CREATE TABLE IF NOT EXISTS users
(
    userid bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    password character varying(255),
    username character varying(255),
    CONSTRAINT users_pkey PRIMARY KEY (id)
)